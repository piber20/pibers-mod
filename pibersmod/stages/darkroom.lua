function PibersMod:BackdropIsOpen(backdrop)
	return backdrop == BackdropType.DARKROOM or backdrop == BackdropType.MEGA_SATAN or backdrop == BackdropType.DUNGEON_BEAST
end

function PibersMod:PreRenderFloorDarkRoom(color)
	local game = Game()
	local room = game:GetRoom()
	local backdropType = room:GetBackdropType()
	if backdropType == BackdropType.DARKROOM then
		local lastGrid = room:GetGridSize()-1
		local gridWidth = room:GetGridWidth()
		local roomShape = room:GetRoomShape()
		local useTable = PibersMod.DarkroomFrames
		local useTableMax = PibersMod.DarkroomFramesMax
		local isWide = roomShape == RoomShape.ROOMSHAPE_2x1 or roomShape == RoomShape.ROOMSHAPE_IIH or roomShape == RoomShape.ROOMSHAPE_2x2 or roomShape == RoomShape.ROOMSHAPE_LTL or roomShape == RoomShape.ROOMSHAPE_LTR or roomShape == RoomShape.ROOMSHAPE_LBL or roomShape == RoomShape.ROOMSHAPE_LBR
		local isShort = roomShape == RoomShape.ROOMSHAPE_1x1 or roomShape == RoomShape.ROOMSHAPE_IH or roomShape == RoomShape.ROOMSHAPE_IV or roomShape == RoomShape.ROOMSHAPE_2x1 or roomShape == RoomShape.ROOMSHAPE_IIH
		if isWide then
			useTable = PibersMod.DarkroomFramesWide
		end

		local topleft = 0
		while useTable[topleft] == nil do
			topleft = topleft + 1
		end
		local topright = topleft
		while useTable[topright] ~= nil do
			topright = topright + 1
		end
		topright = topright - 1
		local bottomleft = topleft
		while useTable[bottomleft] ~= nil do
			bottomleft = bottomleft + gridWidth
		end
		bottomleft = bottomleft - gridWidth
		local bottomright = bottomleft
		while useTable[bottomright] ~= nil do
			bottomright = bottomright + 1
		end
		bottomright = bottomright - 1

		for i,v in pairs(useTable) do
			local floorPos = room:GetGridPosition(i)
			if room:IsPositionInRoom(floorPos,1) and i <= lastGrid then
				local torender1 = nil
				local torender2 = nil
				local torender3 = nil
				local torender4 = nil
				local grid = room:GetGridEntity(i)
				local gridCollision = GridCollisionClass.COLLISION_NONE
				local gridLeft = room:GetGridEntity(i-1)
				local gridLeftCollision = GridCollisionClass.COLLISION_NONE
				local gridRight = room:GetGridEntity(i+1)
				local gridRightCollision = GridCollisionClass.COLLISION_NONE
				local gridUp = room:GetGridEntity(i-gridWidth)
				local gridUpCollision = GridCollisionClass.COLLISION_NONE
				local gridDown = room:GetGridEntity(i+gridWidth)
				local gridDownCollision = GridCollisionClass.COLLISION_NONE

				if grid then
					local gridType = grid:GetType()
					if gridType == GridEntityType.GRID_WALL or gridType == GridEntityType.GRID_DOOR then
						gridCollision = GridCollisionClass.COLLISION_PIT
					else
						gridCollision = grid.CollisionClass
					end
				end

				if room:GetGridCollision(i) ~= GridCollisionClass.COLLISION_PIT then
					if gridLeft then
						local gridType = gridLeft:GetType()
						if gridType == GridEntityType.GRID_WALL or gridType == GridEntityType.GRID_DOOR then
							gridLeftCollision = GridCollisionClass.COLLISION_PIT
						else
							gridLeftCollision = gridLeft.CollisionClass
						end
					end
					if gridRight then
						local gridType = gridRight:GetType()
						if gridType == GridEntityType.GRID_WALL or gridType == GridEntityType.GRID_DOOR then
							gridRightCollision = GridCollisionClass.COLLISION_PIT
						else
							gridRightCollision = gridRight.CollisionClass
						end
					end
					if gridUp then
						local gridType = gridUp:GetType()
						if gridType == GridEntityType.GRID_WALL or gridType == GridEntityType.GRID_DOOR then
							gridUpCollision = GridCollisionClass.COLLISION_PIT
						else
							gridUpCollision = gridUp.CollisionClass
						end
					end
					if gridDown then
						local gridType = gridDown:GetType()
						if gridType == GridEntityType.GRID_WALL or gridType == GridEntityType.GRID_DOOR then
							gridDownCollision = GridCollisionClass.COLLISION_PIT
						else
							gridDownCollision = gridDown.CollisionClass
						end
					end

					local didLeftRight = false
					if gridLeftCollision == GridCollisionClass.COLLISION_PIT then
						didLeftRight = true
						if gridUpCollision == GridCollisionClass.COLLISION_PIT then
							torender1 = topleft
							if gridDownCollision == GridCollisionClass.COLLISION_PIT then
								torender2 = bottomleft
							end
						elseif gridDownCollision == GridCollisionClass.COLLISION_PIT then
							torender1 = bottomleft
						else
							torender1 = i
							while useTable[torender1] ~= nil do
								torender1 = torender1 - 1
							end
							if useTable[torender1] == nil then
								torender1 = torender1 + 1
							end
						end
					end

					if gridRightCollision == GridCollisionClass.COLLISION_PIT then
						didLeftRight = true
						if gridUpCollision == GridCollisionClass.COLLISION_PIT then
							torender3 = topright
							if gridDownCollision == GridCollisionClass.COLLISION_PIT then
								torender4 = bottomright
							end
						elseif gridDownCollision == GridCollisionClass.COLLISION_PIT then
							torender3 = bottomright
						else
							torender3 = i
							while useTable[torender3] ~= nil do
								torender3 = torender3 + 1
							end
							if useTable[torender3] == nil then
								torender3 = torender3 - 1
							end
						end
					end

					if not didLeftRight then
						if gridUpCollision == GridCollisionClass.COLLISION_PIT then
							torender1 = i
							while useTable[torender1] ~= nil do
								torender1 = torender1 - gridWidth
							end
							if useTable[torender1] == nil then
								torender1 = torender1 + gridWidth
							end
						end
						if gridDownCollision == GridCollisionClass.COLLISION_PIT then
							torender2 = i
							while useTable[torender2] ~= nil do
								torender2 = torender2 + gridWidth
							end
							if useTable[torender2] == nil then
								torender2 = torender2 - gridWidth
							end
						end
					end

					PibersMod.DarkroomSpriteFloor:SetFrame(v)
					PibersMod.DarkroomSpriteFloor:Render(Isaac.WorldToScreen(floorPos))

					if torender1 then
						local torender1Frame = useTable[torender1]
						PibersMod.DarkroomSpriteEdge:SetFrame(torender1Frame)
						PibersMod.DarkroomSpriteEdge:Render(Isaac.WorldToScreen(floorPos))
					end
					if torender2 then
						local torender2Frame = useTable[torender2]
						PibersMod.DarkroomSpriteEdge:SetFrame(torender2Frame)
						PibersMod.DarkroomSpriteEdge:Render(Isaac.WorldToScreen(floorPos))
					end
					if torender3 then
						local torender3Frame = useTable[torender3]
						PibersMod.DarkroomSpriteEdge:SetFrame(torender3Frame)
						PibersMod.DarkroomSpriteEdge:Render(Isaac.WorldToScreen(floorPos))
					end
					if torender4 then
						local torender4Frame = useTable[torender4]
						PibersMod.DarkroomSpriteEdge:SetFrame(torender4Frame)
						PibersMod.DarkroomSpriteEdge:Render(Isaac.WorldToScreen(floorPos))
					end
				end
			end
		end
	end
end
PibersMod:AddCallback(ModCallbacks.MC_PRE_BACKDROP_RENDER_FLOOR, PibersMod.PreRenderFloorDarkRoom)

function PibersMod:OnCraterInit(effect)
	local game = Game()
	local room = game:GetRoom()
	if room:GetBackdropType() == BackdropType.DARKROOM then
		effect:Remove()
	end
end
PibersMod:AddCallback(ModCallbacks.MC_POST_EFFECT_INIT, PibersMod.OnCraterInit, EffectVariant.BOMB_CRATER)

function PibersMod:PostWallDoorUpdate(gridEntity)
	if gridEntity.CollisionClass == GridCollisionClass.COLLISION_WALL then
		local game = Game()
		local room = game:GetRoom()
		if PibersMod:BackdropIsOpen(room:GetBackdropType()) then
			gridEntity.CollisionClass = GridCollisionClass.COLLISION_PIT
		end
	end
end
PibersMod:AddCallback(ModCallbacks.MC_POST_GRID_ENTITY_WALL_RENDER, PibersMod.PostWallDoorUpdate, GridEntityType.GRID_WALL)
PibersMod:AddCallback(ModCallbacks.MC_POST_GRID_ENTITY_DOOR_UPDATE, PibersMod.PostWallDoorUpdate, GridEntityType.GRID_DOOR)

function PibersMod:OnNewRoomDarkRoom()
	local game = Game()
	if MinimapAPI then
		local level = game:GetLevel()
		for _, entity in pairs(Isaac.FindByType(EntityType.ENTITY_EFFECT, EffectVariant.DIRT_PATCH, -1, false, false)) do
			local minimapRoom = MinimapAPI:GetRoomByIdx(level:GetCurrentRoomIndex())
			if not minimapRoom.PermanentIcons then
				minimapRoom.PermanentIcons = {"Grave"}
			end
			break
		end
	end
end
PibersMod:AddCallback(ModCallbacks.MC_POST_NEW_ROOM, PibersMod.OnNewRoomDarkRoom)

function PibersMod:OnPlayerRenderDarkRoom(player, offset)
	local game = Game()
	local room = game:GetRoom()
	if PibersMod:BackdropIsOpen(room:GetBackdropType()) then
		local posx = player.Position.X
		local posy = player.Position.Y
		local velx = player.Velocity.X
		local vely = player.Velocity.Y
		local minx = -10
		local maxx = 610
		local miny = 70
		local maxy = 450
		local roomShape = room:GetRoomShape()
		if roomShape == RoomShape.ROOMSHAPE_2x1 or roomShape == RoomShape.ROOMSHAPE_IIH or roomShape == RoomShape.ROOMSHAPE_2x2 or roomShape == RoomShape.ROOMSHAPE_LTL or roomShape == RoomShape.ROOMSHAPE_LTR or roomShape == RoomShape.ROOMSHAPE_LBL or roomShape == RoomShape.ROOMSHAPE_LBR then
			maxx = 1130
		end
		if roomShape == RoomShape.ROOMSHAPE_1x2 or roomShape == RoomShape.ROOMSHAPE_IIV or roomShape == RoomShape.ROOMSHAPE_2x2 or roomShape == RoomShape.ROOMSHAPE_LTL or roomShape == RoomShape.ROOMSHAPE_LTR or roomShape == RoomShape.ROOMSHAPE_LBL or roomShape == RoomShape.ROOMSHAPE_LBR then
			maxy = 730
		end

		posx = math.max(minx,math.min(maxx, posx))
		posy = math.max(miny,math.min(maxy, posy))
		if posx + velx ~= math.max(minx,math.min(maxx, posx+velx)) then
			velx = 0
		end
		if posy + vely ~= math.max(miny,math.min(maxy, posy+vely)) then
			vely = 0
		end
		if posx ~= player.Position.X or posy ~= player.Position.Y then
			player.Position = Vector(posx, posy)
		end
		if velx ~= player.Velocity.X or vely ~= player.Velocity.Y then
			player.Velocity = Vector(velx, vely)
		end
	end

	local heldSprite = player:GetHeldSprite()
	if heldSprite then
		local heldFilename = string.lower(heldSprite:GetFilename())
		if heldFilename == "gfx/ui/ui_cardspills.anm2" then
			local heldCardID = heldSprite:GetOverlayFrame()
			local heldCardData = XMLData.GetEntryById(XMLNode.CARD, heldCardID)
			if heldCardData and heldCardData.type and string.lower(heldCardData.type) == "rune" and tonumber(heldCardData.pickup) then
				local heldCardXML = XMLData.GetEntityByTypeVarSub(EntityType.ENTITY_PICKUP, PickupVariant.PICKUP_TAROTCARD, tonumber(heldCardData.pickup))
				if heldCardXML and heldCardXML.anm2path then
					heldSprite:Load("gfx/" .. heldCardXML.anm2path, true)
					heldSprite:SetFrame("HUD", 0)
				end
			end
		elseif string.find(heldFilename, "/content/gfx/ui_cardfronts.anm2") then
			local heldCardHUD = string.lower(heldSprite:GetOverlayAnimation())
			if heldCardHUD then
				for cardID=0, XMLData.GetNumEntries(XMLNode.CARD) do
					local cardData = XMLData.GetEntryById(XMLNode.CARD, cardID)
					if cardData and cardData.hud and string.lower(cardData.hud) == heldCardHUD then
						if cardData.type and string.lower(cardData.type) == "rune" and tonumber(cardData.pickup) then
							local heldCardXML = XMLData.GetEntityByTypeVarSub(EntityType.ENTITY_PICKUP, PickupVariant.PICKUP_TAROTCARD, tonumber(cardData.pickup))
							if heldCardXML and heldCardXML.anm2path then
								heldSprite:Load("gfx/" .. heldCardXML.anm2path, true)
								heldSprite:SetFrame("HUD", 0)
							end
						end
						break
					end
				end
			end
		end
	end
end
PibersMod:AddCallback(ModCallbacks.MC_POST_PLAYER_RENDER, PibersMod.OnPlayerRenderDarkRoom)
